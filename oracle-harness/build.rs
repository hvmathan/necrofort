//! Builds the gfortran oracle used by `tests/differential_pbt.rs`.
//!
//! The upstream BioUMAT file contains a routine (`SDVINI`) that does not compile
//! under `-std=legacy`, so the routines under test are extracted verbatim into
//! `$OUT_DIR/bioumat_kernels.f`, compiled with `gfortran -std=legacy -c`, archived,
//! and linked into test binaries only. The upstream file is never modified.
//!
//! For `wasm32-*` targets this script does nothing: the oracle is host-only.

use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

const SOURCE: &str = "../targets/bioumat/SUBROUTINES.FOR";
const ROUTINES: &[&str] = &["TRANSPOSE", "DETERMINANT", "VMATMUL", "TENF"];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={SOURCE}");
    println!("cargo:rerun-if-env-changed=FC");
    println!("cargo:rerun-if-env-changed=AR");

    let target = env::var("TARGET").expect("TARGET is set by cargo");
    if target.starts_with("wasm32") {
        return;
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    let source = fs::read_to_string(SOURCE)
        .unwrap_or_else(|e| panic!("cannot read Fortran target {SOURCE}: {e}"));

    let mut kernels = String::from(
        "C     Generated by oracle-harness/build.rs. Routines copied verbatim from\n\
         C     targets/bioumat/SUBROUTINES.FOR (MIT, (c) 2019 Seyed Shayan Sajjadinia).\n",
    );
    for name in ROUTINES {
        kernels.push_str(&extract_routine(&source, name));
    }
    let f_path = out_dir.join("bioumat_kernels.f");
    fs::write(&f_path, kernels).expect("write extracted kernels");

    let obj = out_dir.join("bioumat_kernels.o");
    let fc = env::var("FC").unwrap_or_else(|_| "gfortran".to_string());
    run(
        Command::new(&fc)
            .args(["-std=legacy", "-ffp-contract=off", "-O2", "-fPIC", "-c"])
            .arg(&f_path)
            .arg("-o")
            .arg(&obj),
        &fc,
    );

    let lib = out_dir.join("libbioumat_oracle.a");
    let _ = fs::remove_file(&lib);
    let ar = env::var("AR").unwrap_or_else(|_| "ar".to_string());
    run(Command::new(&ar).arg("crs").arg(&lib).arg(&obj), &ar);

    // Link the oracle into test binaries only; the rlib, cdylib and wasm stay pure Rust.
    println!("cargo:rustc-link-arg-tests={}", lib.display());
}

/// Returns the fixed-form source of `SUBROUTINE <name>` through its `END` line.
fn extract_routine(source: &str, name: &str) -> String {
    let mut out = String::new();
    let mut inside = false;
    for line in source.lines() {
        let is_comment = matches!(line.chars().next(), Some('C' | 'c' | '*' | '!'));
        let stmt = line.get(6..).unwrap_or("").trim();
        if !inside && !is_comment {
            let upper = stmt.to_ascii_uppercase();
            if let Some(rest) = upper.strip_prefix("SUBROUTINE") {
                let rest = rest.trim_start();
                if rest.starts_with(name) && rest[name.len()..].trim_start().starts_with(['(', ' '])
                {
                    inside = true;
                }
            }
        }
        if inside {
            out.push_str(line);
            out.push('\n');
            if !is_comment && stmt.eq_ignore_ascii_case("END") {
                return out;
            }
        }
    }
    panic!("SUBROUTINE {name} not found (or has no END) in {SOURCE}");
}

fn run(cmd: &mut Command, tool: &str) {
    let output = cmd.output().unwrap_or_else(|e| {
        panic!(
            "failed to run `{tool}` ({e}). Install gfortran/binutils or set FC/AR; \
             see .kiro/steering/verification-loop.md"
        )
    });
    if !output.status.success() {
        panic!(
            "`{cmd:?}` failed with {}:\n{}{}",
            output.status,
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
    }
}
